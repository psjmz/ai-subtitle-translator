const WebSocket = require('/Users/jp/.workbuddy/binaries/node/workspace/node_modules/ws');
const http = require('http'); const fs = require('fs');
const PORT = 9333, BASE = 'http://127.0.0.1:3098';
const wait = ms => new Promise(r => setTimeout(r, ms));
const J = p => new Promise((res, rej) => { const r = http.request({ host: '127.0.0.1', port: PORT, path: p, method: 'PUT' }, x => { let d = ''; x.on('data', c => d += c); x.on('end', () => { try { res(JSON.parse(d)); } catch (e) { rej(new Error(d.slice(0, 200))); } }); }); r.on('error', rej); r.end(); });
(async () => {
  const v = await J('/json/new?' + encodeURIComponent('about:blank'));
  const ws = new WebSocket(v.webSocketDebuggerUrl, { perMessageDeflate: false });
  let id = 0; const wt = new Map();
  await new Promise(r => ws.on('open', r));
  ws.on('message', m => { const g = JSON.parse(m); if (g.id && wt.has(g.id)) { const q = wt.get(g.id); wt.delete(g.id); g.error ? q.rej(new Error(JSON.stringify(g.error))) : q.res(g.result); } });
  const send = (m, p) => new Promise((res, rej) => { const i = ++id; wt.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p || {} })); });
  const ev = async e => { const r = await send('Runtime.evaluate', { expression: e, returnByValue: true, awaitPromise: true }); if (r.exceptionDetails) throw new Error((r.exceptionDetails.exception || {}).description || r.exceptionDetails.text); return r.result.value; };
  await send('Page.enable'); await send('Network.setCacheDisabled', { cacheDisabled: true });
  await send('Page.navigate', { url: BASE + '/merge.html' });
  await wait(2500);
  await send('Emulation.setDeviceMetricsOverride', { width: 1400, height: 1000, deviceScaleFactor: 1, mobile: false });
  await wait(400);
  await ev(`(function(){
    S.mode='merge'; S.srcName='a.srt'; S.dstName='b.srt';
    S.rows=[{start:1000,end:3000,en:'Hello',zh:'你好'},{start:4000,end:6000,en:'Hi',zh:'嗨'}];
    S.report={pairs:2,onlySrc:[],onlyDst:[],merged:0};
    ensureStyle(); S.editFp=calcEditFp(); renderReport();
    document.getElementById('expFmt').value='vttStyle';
    document.getElementById('expFmt').dispatchEvent(new Event('change',{bubbles:true}));
    var ap=document.getElementById('assPanel'); if(ap) ap.open=true;
    var vp=document.getElementById('mVttPanel')||{open:false,getBoundingClientRect:()=>document.getElementById('assPanel').getBoundingClientRect()}; if(vp) vp.open=true;
    return 1;})()`);
  await wait(400);
  await ev(`var p=document.getElementById('assPanel'); window.scrollTo(0, p.getBoundingClientRect().top + window.scrollY - 70)`);
  await wait(300);
  let r = await send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('_shot272-ass.png', Buffer.from(r.data, 'base64'));
  await ev(`var p=document.getElementById('mVttPanel')||{open:false,getBoundingClientRect:()=>document.getElementById('assPanel').getBoundingClientRect()}; if(p){p.open=true;} window.scrollTo(0, p.getBoundingClientRect().top + window.scrollY - 70)`);
  await wait(300);
  r = await send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('_shot272-vtt.png', Buffer.from(r.data, 'base64'));
  console.log('saved');
  ws.close(); process.exit(0);
})().catch(e => { console.error('FATAL', e); process.exit(2); });
